// Regenerates docs/changelog.md from the plugin's own root CHANGELOG.md
// (one level up) so the two never drift apart — this file is NOT hand-
// edited; edit ../../CHANGELOG.md instead and rerun this script (or just
// `npm start`/`npm run build`, which run it automatically via the
// presync-changelog/prestart/prebuild hooks in package.json).
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const websiteRoot = path.join(__dirname, '..');

const sourcePath = path.join(websiteRoot, '..', 'CHANGELOG.md');
const targetPath = path.join(websiteRoot, 'docs', 'changelog.md');

const source = fs.readFileSync(sourcePath, 'utf-8');

const frontMatter = `---
sidebar_position: 6
title: Changelog
toc_max_heading_level: 2
custom_edit_url: https://github.com/shichishima/obsidian-universal-cursor-hotkeys/edit/main/CHANGELOG.md
show_mode_tabs: true
# Generated by scripts/sync-changelog.mjs from ../CHANGELOG.md — do not edit this file directly.
---

`;

fs.writeFileSync(targetPath, frontMatter + source);
console.log(`Synced ${path.relative(websiteRoot, targetPath)} from ${path.relative(websiteRoot, sourcePath)}`);
